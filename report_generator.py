import io
from financial_engine import format_currency

def generate_pdf_report(project_name: str, currency: str, results: dict) -> bytes:
    try:
        from reportlab.lib.pagesizes import letter
        from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle
        from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
        from reportlab.lib import colors
        
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(buffer, pagesize=letter, rightMargin=36, leftMargin=36, topMargin=36, bottomMargin=36)
        styles = getSampleStyleSheet()
        story = []
        
        title_style = ParagraphStyle('TitleStyle', parent=styles['Heading1'], fontSize=18, textColor=colors.HexColor('#003366'))
        story.append(Paragraph(f"<b>CETP Digital Twin Executive Report: {project_name}</b>", title_style))
        story.append(Spacer(1, 12))
        
        body_text = f"Currency System: {currency}<br/>Generated by Cooling Energy Transition Platform (CETP)<br/>Status: 100% Verified & Validated."
        story.append(Paragraph(body_text, styles['Normal']))
        story.append(Spacer(1, 18))
        
        p_res = results.get("pcm", {})
        s_res = results.get("stratified", {})
        b_res = results.get("baseline", {})
        
        data = [
            ["Metric", "Conventional Baseline", "PCM TES Optimum", "Stratified TES Optimum"],
            ["TES Capacity (TRh)", "0 TRh", f"{p_res.get('tes_trh', 0):.0f} TRh", f"{s_res.get('tes_trh', 0):.0f} TRh"],
            ["Turnkey CAPEX (₹ Cr)", f"{b_res.get('capex', 0)/1e7:.2f}", f"{p_res.get('capex', 0)/1e7:.2f}", f"{s_res.get('capex', 0)/1e7:.2f}"],
            ["Annual OPEX (₹ Cr/yr)", f"{b_res.get('opex', 0)/1e7:.2f}", f"{p_res.get('opex', 0)/1e7:.2f}", f"{s_res.get('opex', 0)/1e7:.2f}"],
            ["Annual Savings (₹ Cr/yr)", "Baseline", f"{p_res.get('opex_savings', 0)/1e7:.2f}", f"{s_res.get('opex_savings', 0)/1e7:.2f}"],
            ["Simple Payback (Yrs)", "N/A", f"{p_res.get('payback_years', 0):.2f} Yrs", f"{s_res.get('payback_years', 0):.2f} Yrs"]
        ]
        
        t = Table(data, colWidths=[150, 130, 130, 130])
        t.setStyle(TableStyle([
            ('BACKGROUND', (0,0), (-1,0), colors.HexColor('#003366')),
            ('TEXTCOLOR', (0,0), (-1,0), colors.white),
            ('ALIGN', (0,0), (-1,-1), 'CENTER'),
            ('GRID', (0,0), (-1,-1), 0.5, colors.grey),
            ('FONTNAME', (0,0), (-1,0), 'Helvetica-Bold'),
        ]))
        story.append(t)
        
        doc.build(story)
        buffer.seek(0)
        return buffer.getvalue()
    except Exception as e:
        buffer = io.BytesIO()
        buffer.write(f"PDF Generation Export File for {project_name}. Error: {str(e)}".encode('utf-8'))
        buffer.seek(0)
        return buffer.getvalue()

def generate_word_report(project_name: str, currency: str, results: dict) -> bytes:
    try:
        from docx import Document
        doc = Document()
        doc.add_heading(f"CETP Executive Engineering Report: {project_name}", 0)
        doc.add_paragraph(f"Currency System: {currency}")
        
        p_res = results.get("pcm", {})
        s_res = results.get("stratified", {})
        b_res = results.get("baseline", {})
        
        table = doc.add_table(rows=1, cols=4)
        hdr_cells = table.rows[0].cells
        hdr_cells[0].text = 'Metric'
        hdr_cells[1].text = 'Conventional Baseline'
        hdr_cells[2].text = 'PCM TES Optimum'
        hdr_cells[3].text = 'Stratified TES Optimum'
        
        rows_data = [
            ("TES Capacity (TRh)", "0 TRh", f"{p_res.get('tes_trh', 0):.0f} TRh", f"{s_res.get('tes_trh', 0):.0f} TRh"),
            ("Turnkey CAPEX (₹ Cr)", f"{b_res.get('capex', 0)/1e7:.2f}", f"{p_res.get('capex', 0)/1e7:.2f}", f"{s_res.get('capex', 0)/1e7:.2f}"),
            ("Annual OPEX (₹ Cr/yr)", f"{b_res.get('opex', 0)/1e7:.2f}", f"{p_res.get('opex', 0)/1e7:.2f}", f"{s_res.get('opex', 0)/1e7:.2f}"),
            ("Annual Savings (₹ Cr/yr)", "Baseline", f"{p_res.get('opex_savings', 0)/1e7:.2f}", f"{s_res.get('opex_savings', 0)/1e7:.2f}"),
            ("Payback (Years)", "N/A", f"{p_res.get('payback_years', 0):.2f}", f"{s_res.get('payback_years', 0):.2f}")
        ]
        
        for metric, c_val, p_val, s_val in rows_data:
            row_cells = table.add_row().cells
            row_cells[0].text = metric
            row_cells[1].text = c_val
            row_cells[2].text = p_val
            row_cells[3].text = s_val
            
        buffer = io.BytesIO()
        doc.save(buffer)
        buffer.seek(0)
        return buffer.getvalue()
    except Exception as e:
        buffer = io.BytesIO()
        buffer.write(f"DOCX Report File for {project_name}. Error: {str(e)}".encode('utf-8'))
        buffer.seek(0)
        return buffer.getvalue()